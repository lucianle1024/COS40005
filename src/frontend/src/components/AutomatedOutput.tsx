import { useState } from 'react';
import type { InvestigationCase } from '../api/generated';
import { SourceLinks } from './SourceLinks';
export function AutomatedOutput({
  data,
  onInspect,
  connected = false,
}: {
  data: InvestigationCase;
  connected?: boolean;
  onInspect: (id: string) => void;
}) {
  const [showAllSources, setShowAllSources] = useState(false);
  const output = data.automatedAssessment;
  const sourceIds = output.evidenceIds;
  const signalSummary = output.rationale.match(
    /^(?:Multiple rule signals|One rule signal) found: (.+)$/,
  );
  const signals = signalSummary?.[1].replace(/\.$/, '').split('; ');
  const previewLimit = 8;
  const namedSources = new Set(output.rationale.match(/\bEVENT-\d+\b/g) ?? []);
  const previewSources = [
    ...sourceIds.filter((id) => namedSources.has(id)),
    ...sourceIds.filter((id) => !namedSources.has(id)),
  ].slice(0, previewLimit);
  const hasMoreSources = sourceIds.length > previewLimit;
  return (
    <section className="panel automated-panel" aria-labelledby="automated-title">
      <div className="panel-heading">
        <div>
          <span className="step-number">02</span>
          <h2 id="automated-title">Automated output</h2>
        </div>
        <span className="badge badge-neutral">Read only</span>
      </div>
      <div className="panel-body">
        <p className="panel-intro">
          {connected
            ? 'Case 1 assessment generated by the backend’s fixed rules.'
            : 'Fixed output for the AI-only workflow demonstration.'}
        </p>
        <article className="automated-result">
          <p className="assessment-label">Case assessment</p>
          <h3 className={`badge badge-${output.classification} assessment-verdict`}>
            {output.classification}
          </h3>
          <h4 className="assessment-section">Why it got this verdict</h4>
          {signals ? (
            <ul className="assessment-signals">
              {signals.map((signal) => (
                <li key={signal}>{signal}</li>
              ))}
            </ul>
          ) : (
            <p>{output.rationale}</p>
          )}
          <h4 className="assessment-section">Supporting evidence</h4>
          <div id="automated-sources">
            <SourceLinks
              ids={hasMoreSources && !showAllSources ? previewSources : sourceIds}
              records={data.evidence}
              onInspect={onInspect}
            />
          </div>
          {hasMoreSources && (
            <button
              className="text-button"
              type="button"
              aria-expanded={showAllSources}
              aria-controls="automated-sources"
              onClick={() => setShowAllSources(!showAllSources)}
            >
              {showAllSources ? 'Show fewer sources' : `Show all ${sourceIds.length} sources`}
            </button>
          )}
          <h3 className="limitations-heading">Limits of this output</h3>
          <ul>
            {output.limitations.map((item) => (
              <li key={item}>{item}</li>
            ))}
          </ul>
        </article>
        <div className="read-only-note">
          <strong>No analyst edits in this mode.</strong>
          <p>
            {connected
              ? 'The completed assessment is saved with the session.'
              : 'The eventual AI-only pipeline and its timing/scoring belong to backend integration. This screen does not run or evaluate a model.'}
          </p>
        </div>
      </div>
    </section>
  );
}
